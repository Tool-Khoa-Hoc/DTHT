export const THPT_CATEGORY_KEYS = [
  'toan',
  'ly',
  'hoa',
  'sinh',
  'van',
  'anh',
  'su',
  'dia',
  'gdcd',
  'tin',
  'khac',
];

export const UNI_CATEGORY_KEYS = [
  'giai_tich',
  'lap_trinh',
  'kinh_te',
  'kien_truc',
  'khac',
];

const KNOWN_CATEGORY_SET = new Set([...THPT_CATEGORY_KEYS, ...UNI_CATEGORY_KEYS]);

export function getLocalizedDocCategories(educationLevel, t) {
  const keys = educationLevel === 'university' ? UNI_CATEGORY_KEYS : THPT_CATEGORY_KEYS;
  return keys.map((value) => ({
    value,
    label: t(`docCategories.${value}`),
  }));
}

export function getLocalizedCategoryLabel(rawCategory, t) {
  if (!rawCategory) return '';
  const normalized = String(rawCategory).trim().toLowerCase();
  if (KNOWN_CATEGORY_SET.has(normalized)) {
    return t(`docCategories.${normalized}`);
  }
  return String(rawCategory);
}

export function getLocalizedEducationLevel(rawLevel, t) {
  const normalized = String(rawLevel || 'thpt').trim().toLowerCase();
  if (normalized === 'university' || normalized === 'uni' || normalized === 'sv') {
    return t('docCategories.levelUniversityShort');
  }
  return t('docCategories.levelThptShort');
}

